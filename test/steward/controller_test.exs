defmodule Steward.ControllerTest do
  use Steward.DataCase
  alias Steward.Controller
  alias Steward.MockController

  setup do
    stub_defaults(MockController)
    :ok
  end

  describe "use Steward.Controller" do
    test "defines shorthands for the controller's resources" do
      assert {:ok, resource} = Steward.TestController.create_resource()
      assert resource.controller == "Steward.TestController"

      assert {:ok, %{id: id}} = Steward.TestController.get_resource(resource.id)
      assert id == resource.id
    end
  end

  describe "validate_opts!/1" do
    test "returns valid options" do
      opts = [steward: Steward.TestSteward, reconcile_interval: :infinity]

      assert Controller.validate_opts!(opts) == opts
    end

    test "raises without :steward" do
      assert_raise ArgumentError, ~r/missing required option :steward/, fn ->
        Controller.validate_opts!(reconcile_interval: 1_000)
      end
    end

    test "raises for an invalid :reconcile_interval" do
      assert_raise ArgumentError, ~r/:reconcile_interval/, fn ->
        Controller.validate_opts!(steward: Steward.TestSteward, reconcile_interval: -1)
      end
    end

    test "raises for unknown options" do
      assert_raise ArgumentError, ~r/unknown option :foo/, fn ->
        Controller.validate_opts!(steward: Steward.TestSteward, foo: 1)
      end
    end
  end

  describe "create_resource/3" do
    test "inserts a resource with an autogenerated id and controller string" do
      assert {:ok, resource} = Controller.create_resource(MockController)

      assert is_binary(resource.id)
      assert resource.controller == "Steward.MockController"
      assert resource.meta == %{}
    end

    test "accepts custom meta" do
      assert {:ok, resource} =
               Controller.create_resource(MockController, %{meta: %{"key" => "val"}})

      assert resource.meta == %{"key" => "val"}
    end

    test "accepts a caller-supplied id" do
      id = Ecto.UUID.generate()

      assert {:ok, resource} = Controller.create_resource(MockController, %{id: id})

      assert resource.id == id
    end

    test "returns an error changeset for an existing id" do
      {:ok, resource} = Controller.create_resource(MockController)

      assert {:error, changeset} = Controller.create_resource(MockController, %{id: resource.id})
      assert {"has already been taken", _} = changeset.errors[:id]
    end

    test "schedules the resource by default" do
      assert {:ok, resource} = Controller.create_resource(MockController)

      assert resource.reconciliation_state == :scheduled
      assert resource.reconciliation_due_at
    end

    test "creates an idle resource with schedule: false" do
      assert {:ok, resource} = Controller.create_resource(MockController, %{}, schedule: false)

      assert resource.reconciliation_state == :idle
      assert resource.reconciliation_due_at == nil
      assert resource.reconciliation_state_set_at
      assert Map.delete(resource, :__meta__) == Map.delete(reload(resource), :__meta__)
    end
  end

  describe "upsert_resource/3" do
    test "creates a resource for a new id" do
      id = Ecto.UUID.generate()

      assert {:ok, resource} =
               Controller.upsert_resource(MockController, %{id: id, meta: %{"key" => "val"}})

      assert resource.id == id
      assert resource.meta == %{"key" => "val"}
      assert resource.reconciliation_state == :scheduled
      assert Map.delete(resource, :__meta__) == Map.delete(reload(resource), :__meta__)
    end

    test "schedules an existing resource and keeps its meta" do
      resource = insert_idle_resource(%{meta: %{"key" => "old"}})

      assert {:ok, upserted} =
               Controller.upsert_resource(MockController, %{
                 id: resource.id,
                 meta: %{"key" => "new"}
               })

      assert upserted.reconciliation_state == :scheduled
      assert upserted.reconciliation_due_at
      assert upserted.meta == %{"key" => "old"}
      assert upserted.inserted_at == resource.inserted_at
      assert DateTime.compare(upserted.updated_at, resource.updated_at) == :gt
      assert Map.delete(upserted, :__meta__) == Map.delete(reload(resource), :__meta__)
    end

    test "sets due_at but keeps the state of an existing resource in reconciliation" do
      set_at = from_now(-10)

      resource =
        insert_resource(%{
          reconciliation_state: :reconciling,
          reconciliation_state_set_at: set_at,
          reconciliation_due_at: nil
        })

      assert {:ok, upserted} = Controller.upsert_resource(MockController, %{id: resource.id})

      assert upserted.reconciliation_state == :reconciling
      assert upserted.reconciliation_state_set_at == set_at
      assert upserted.reconciliation_due_at
    end

    test "creates an idle resource with schedule: false" do
      assert {:ok, resource} =
               Controller.upsert_resource(MockController, %{id: Ecto.UUID.generate()},
                 schedule: false
               )

      assert resource.reconciliation_state == :idle
      assert resource.reconciliation_due_at == nil
    end

    test "leaves an existing resource unscheduled with schedule: false" do
      resource = insert_idle_resource()

      assert {:ok, upserted} =
               Controller.upsert_resource(MockController, %{id: resource.id}, schedule: false)

      assert upserted.reconciliation_state == :idle
      assert upserted.reconciliation_due_at == nil
      assert Map.delete(upserted, :__meta__) == Map.delete(reload(resource), :__meta__)
    end

    test "returns an error changeset for a cancelled resource with schedule: false" do
      resource = insert_idle_resource(%{cancelled_at: from_now(-10)})

      assert {:error, changeset} =
               Controller.upsert_resource(MockController, %{id: resource.id}, schedule: false)

      assert {"is cancelled", _} = changeset.errors[:cancelled_at]
    end

    test "returns an error changeset for a cancelled resource and leaves it alone" do
      resource = insert_idle_resource(%{cancelled_at: from_now(-10)})

      assert {:error, changeset} = Controller.upsert_resource(MockController, %{id: resource.id})
      assert {"is cancelled", _} = changeset.errors[:cancelled_at]

      assert reload(resource).reconciliation_state == :idle
    end

    test "is defined as a shorthand" do
      id = Ecto.UUID.generate()

      assert {:ok, %{id: ^id}} = Steward.TestController.upsert_resource(%{id: id})
      assert {:ok, %{id: ^id}} = Steward.TestController.upsert_resource(%{id: id})
    end
  end

  describe "process_resource/4" do
    test "calls fun with the loaded object and returns its result" do
      resource = insert_idle_resource()
      resource_id = resource.id
      expect(MockController, :load, fn %{id: ^resource_id} -> {:ok, :loaded} end)

      assert {:ok, :some_value} =
               Controller.process_resource(MockController, resource, fn :loaded ->
                 {false, {:ok, :some_value}}
               end)

      refute scheduled?(resource)
    end

    test "schedules the resource when fun asks for it" do
      resource = insert_idle_resource()

      assert :ok = Controller.process_resource(MockController, resource, fn _ -> {true, :ok} end)
      assert scheduled?(resource)
    end

    test "schedules the resource and re-raises when fun raises, throws or exits" do
      for {kind, fun} <- [
            error: fn -> raise "boom" end,
            throw: fn -> throw(:boom) end,
            exit: fn -> exit(:boom) end
          ] do
        resource = insert_idle_resource()

        assert {^kind, _reason} =
                 (try do
                    Controller.process_resource(MockController, resource, fn _ -> fun.() end)
                  catch
                    kind, reason -> {kind, reason}
                  end)

        assert scheduled?(resource)
      end
    end

    test "schedules the resource and raises when fun returns an invalid value" do
      resource = insert_idle_resource()

      assert_raise MatchError, fn ->
        Controller.process_resource(MockController, resource, fn _ -> :invalid end)
      end

      assert scheduled?(resource)
    end

    test "doesn't schedule the resource on errors with schedule_on_error: false" do
      resource = insert_idle_resource()

      assert_raise RuntimeError, "boom", fn ->
        Controller.process_resource(MockController, resource, fn _ -> raise "boom" end,
          schedule_on_error: false
        )
      end

      refute scheduled?(resource)
    end

    test "returns :cancelled for a cancelled resource without loading it" do
      resource = insert_idle_resource(%{cancelled_at: from_now(-10)})
      expect(MockController, :load, 0, fn _ -> flunk("load must not be called") end)

      assert :cancelled =
               Controller.process_resource(MockController, resource, fn _ ->
                 flunk("fun must not be called")
               end)

      refute scheduled?(resource)
    end

    test "cancels the resource and returns :cancelled when load/1 returns :cancel" do
      resource = insert_idle_resource()
      expect(MockController, :load, fn _ -> :cancel end)

      assert :cancelled =
               Controller.process_resource(MockController, resource, fn _ ->
                 flunk("fun must not be called")
               end)

      resource = reload(resource)
      assert resource.cancelled_at
      assert resource.reconciliation_state == :scheduled
    end

    test "raises when called within a transaction" do
      resource = insert_idle_resource()

      Steward.TestRepo.transaction(fn ->
        assert_raise RuntimeError, ~r/must not be called within a transaction/, fn ->
          Controller.process_resource(MockController, resource, fn _ ->
            flunk("fun must not be called")
          end)
        end
      end)
    end
  end

  describe "list_resources_by_meta/2" do
    defp ids(resources), do: resources |> Enum.map(& &1.id) |> Enum.sort()

    test "returns resources whose meta contains the given map" do
      a = insert_resource(%{meta: %{"order" => 1, "x" => "y"}})
      b = insert_resource(%{meta: %{"order" => 1}})
      insert_resource(%{meta: %{"order" => 2}})

      assert ids(Controller.list_resources_by_meta(MockController, %{"order" => 1})) ==
               Enum.sort([a.id, b.id])

      assert ids(Controller.list_resources_by_meta(MockController, %{"order" => 1, "x" => "y"})) ==
               [a.id]
    end

    test "matches nested maps partially and atoms as strings" do
      a = insert_resource(%{meta: %{"order" => %{"id" => 1, "v" => 2}}})

      assert ids(Controller.list_resources_by_meta(MockController, %{order: %{id: 1}})) == [a.id]
    end

    test "only returns resources of the controller" do
      insert_resource(%{controller: "Steward.OtherController", meta: %{"order" => 1}})

      assert Controller.list_resources_by_meta(MockController, %{"order" => 1}) == []
    end
  end

  describe "get_resource/2" do
    test "returns the resource by id" do
      created = insert_resource()

      assert {:ok, fetched} = Controller.get_resource(MockController, created.id)
      assert fetched.id == created.id
    end

    test "returns {:error, :not_found} for an unknown id" do
      assert {:error, :not_found} = Controller.get_resource(MockController, Ecto.UUID.generate())
    end

    test "does not return resources belonging to a different controller" do
      other = insert_resource(%{controller: "Steward.OtherController"})

      assert {:error, :not_found} = Controller.get_resource(MockController, other.id)
    end
  end

  describe "schedule_resource!/2" do
    test "schedules an idle resource" do
      resource = insert_idle_resource()

      scheduled = Controller.schedule_resource!(MockController, resource.id)

      assert scheduled.reconciliation_state == :scheduled
      assert scheduled.reconciliation_due_at
      assert Map.delete(scheduled, :__meta__) == Map.delete(reload(resource), :__meta__)
    end

    test "sets due_at but keeps the state of a resource in reconciliation" do
      set_at = from_now(-10)

      resource =
        insert_resource(%{
          reconciliation_state: :reconciling,
          reconciliation_state_set_at: set_at,
          reconciliation_due_at: nil
        })

      scheduled = Controller.schedule_resource!(MockController, resource)

      assert scheduled.reconciliation_state == :reconciling
      assert scheduled.reconciliation_state_set_at == set_at
      assert scheduled.reconciliation_due_at
    end

    test "raises for an unknown resource" do
      assert_raise Steward.ResourceNotFoundError, ~r/not found/, fn ->
        Controller.schedule_resource!(MockController, Ecto.UUID.generate())
      end
    end
  end

  describe "schedule_resources/2" do
    test "schedules the given resources and returns their count" do
      resource_a = insert_idle_resource()
      resource_b = insert_idle_resource()
      other = insert_idle_resource()

      assert {:ok, 2} =
               Controller.schedule_resources(MockController, [
                 resource_a.id,
                 resource_b.id,
                 resource_a.id
               ])

      for resource <- [resource_a, resource_b] do
        reloaded = reload(resource)
        assert reloaded.reconciliation_state == :scheduled
        assert reloaded.reconciliation_due_at
      end

      assert reload(other).reconciliation_state == :idle
    end

    test "returns 0 for no ids" do
      assert Controller.schedule_resources(MockController, []) == {:ok, 0}
    end

    test "ignores unknown ids" do
      resource = insert_idle_resource()

      assert {:ok, 1} =
               Controller.schedule_resources(MockController, [resource.id, Ecto.UUID.generate()])

      assert reload(resource).reconciliation_state == :scheduled
    end
  end

  describe "cancel_resource!/2" do
    test "cancels and schedules the resource" do
      resource = insert_idle_resource()

      cancelled = Controller.cancel_resource!(MockController, resource)

      assert cancelled.cancelled_at
      assert cancelled.reconciliation_state == :scheduled
      assert cancelled.reconciliation_due_at
    end

    test "keeps the original cancelled_at" do
      cancelled_at = from_now(-10)
      resource = insert_resource(%{cancelled_at: cancelled_at})

      cancelled = Controller.cancel_resource!(MockController, resource)

      assert cancelled.cancelled_at == cancelled_at
    end
  end

  describe "resume_resource!/2" do
    test "clears cancelled_at and schedules the resource" do
      resource = insert_idle_resource(%{cancelled_at: from_now(-10)})

      resumed = Controller.resume_resource!(MockController, resource)

      refute resumed.cancelled_at
      assert resumed.reconciliation_state == :scheduled
      assert resumed.reconciliation_due_at
    end

    test "only schedules a resource that isn't cancelled" do
      resource = insert_idle_resource()

      resumed = Controller.resume_resource!(MockController, resource.id)

      refute resumed.cancelled_at
      assert resumed.reconciliation_state == :scheduled
    end

    test "raises for a pruned resource and leaves it alone" do
      resource =
        insert_idle_resource(%{cancelled_at: from_now(-2, :hour), pruned_at: from_now(-1, :hour)})

      assert_raise Steward.ResourceAlreadyPrunedError, ~r/already pruned/, fn ->
        Controller.resume_resource!(MockController, resource)
      end

      resource = reload(resource)
      assert resource.cancelled_at
      assert resource.reconciliation_state == :idle
    end

    test "raises for an unknown resource" do
      assert_raise Steward.ResourceNotFoundError, ~r/not found/, fn ->
        Controller.resume_resource!(MockController, Ecto.UUID.generate())
      end
    end
  end
end
